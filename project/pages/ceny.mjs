export function render() {
  const crumbs = breadcrumbs([['/ceny/', 'Цены']]);

  const cards = PRICES.map((p) => `      <div class="price-card">
        <div class="price-label">${p.tag}</div>
        <div class="price-title">${p.name}</div>
        <div class="price-amount">${p.price}</div>
        <div class="price-time">${p.note}</div>
        <ul class="check-list" style="margin-top:6px;">
${p.works.map((w) => `          <li>${w}</li>`).join('\n')}
        </ul>
        <div class="price-time">${p.term}</div>
        <a href="${p.url}" style="display:inline-block; padding:4px 0; color:var(--accent-bright); font-size:14px; text-decoration:none;">Подробнее →</a>
      </div>`).join('\n');

  const rows = PRICES.map((p) => `        <tr>
          <th scope="row"><a href="${p.url}">${p.name}</a></th>
          <td class="cell-price">${p.price}</td>
          <td class="cell-note">${p.note}</td>
          <td class="cell-term">${p.term}</td>
        </tr>`).join('\n');

  const faq = faqItems(FAQ);

  const body = `<header class="hero" data-screen-label="Цены">
  <div class="wrap">
    ${crumbs.visible}
    <div class="eyebrow">Стоимость</div>
    <h1>Цены на <span class="accent">интернет-маркетинг</span></h1>
    <p class="lead">Прайс частного специалиста: вы платите за работу, а не за офис и отдел продаж. Рекламный бюджет вносится напрямую в кабинет площадки — моей наценки в нём нет.</p>
    <div class="btn-row">
      <a class="btn btn-fill btn-lg" href="/contacts/">Рассчитать под задачу</a>
      <a class="btn btn-ghost btn-lg" href="/keysy/">Посмотреть кейсы</a>
    </div>
  </div>
</header>

<section class="section">
  <div class="wrap">
    <div class="eyebrow reveal">Коротко</div>
    <h2 class="reveal">Прайс на услуги интернет-маркетинга</h2>
    <div class="table-scroll reveal">
      <table class="price-table">
        <caption class="visually-hidden">Стоимость услуг интернет-маркетинга</caption>
        <thead>
          <tr>
            <th scope="col">Услуга</th>
            <th scope="col">Стоимость</th>
            <th scope="col">Что входит в цену</th>
            <th scope="col">Срок запуска</th>
          </tr>
        </thead>
        <tbody>
${rows}
        </tbody>
      </table>
    </div>
    <p style="color:var(--txt-3); font-size:14px; margin-top:18px;">Цены указаны без учёта рекламного бюджета. Итоговая стоимость зависит от объёма работ — назову её после бесплатного разбора задачи.</p>
  </div>
</section>

<section class="section">
  <div class="wrap">
    <div class="eyebrow reveal">Подробно</div>
    <h2 class="reveal">Что входит в каждую услугу</h2>
    <div class="price-grid reveal">
${cards}
    </div>
  </div>
</section>

<section class="section">
  <div class="wrap">
    <div class="eyebrow reveal">Вопросы о цене</div>
    <h2 class="reveal">Вопросы о ценах и оплате</h2>
    <div class="faq-list reveal">
${faq}
    </div>
  </div>
</section>

<section class="section">
  <div class="wrap">
    <div class="cta-final reveal">
      <h2>Рассчитать стоимость под вашу задачу</h2>
      <p>На бесплатной консультации разберу нишу и назову конкретную сумму — по объёму работ, а не по прайсу «в среднем».</p>
      <div class="btn-row">
        <a class="btn btn-fill btn-lg" href="/contacts/">Оставить заявку</a>
        <a class="btn btn-ghost btn-lg" href="https://t.me/Daniil_065" target="_blank" rel="noopener noreferrer">Написать в Telegram</a>
      </div>
    </div>
  </div>
</section>`;

  /* OfferCatalog: витрина услуг с ценами. Цены «от», поэтому используем
     minPrice в PriceSpecification — фиксированный price здесь означал бы
     точную стоимость и расходился бы с текстом страницы. */
  const schema = [
    crumbs.schema,
    {
      '@context': 'https://schema.org',
      '@type': 'OfferCatalog',
      name: 'Услуги интернет-маркетинга',
      url: SITE + meta.path,
      provider: { '@id': SITE + '/#person' },
      itemListElement: PRICES.map((p, i) => {
        const digits = p.price.replace(/[^\d]/g, '');
        return {
          '@type': 'Offer',
          position: i + 1,
          itemOffered: {
            '@type': 'Service',
            name: p.name,
            description: p.works.join('. '),
            url: SITE + p.url,
            provider: { '@id': SITE + '/#person' },
            areaServed: 'RU',
          },
          ...(digits ? {
            priceSpecification: {
              '@type': 'PriceSpecification',
              minPrice: Number(digits),
              priceCurrency: 'RUB',
            },
          } : {}),
        };
      }),
    },
    {
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: FAQ.map(([q, a]) => ({
        '@type': 'Question', name: q,
        acceptedAnswer: { '@type': 'Answer', text: a },
      })),
    },
  ];

  return { body, schema };
}
