/* Доставка заявок с форм.

   ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ НИ ОДНОГО СЕКРЕТА. Файл отдаётся браузеру как
   есть — он лежит по адресу https://karatsapov.ru/lead-config.js и
   открывается любым человеком без всяких инструментов. Токен бота, стоявший
   здесь раньше, был публичным с первого дня: по нему можно было прочитать
   все входящие заявки, писать от имени бота и переименовать его. Именно это
   и произошло.

   Клиентский код в принципе не может хранить секрет: всё, что доходит до
   браузера, доходит и до постороннего. Обфускация, склейка из кусков,
   base64 — не помогают, это те же данные в другом виде.

   Теперь заявка уходит на свой сервер, а он уже разговаривает с MAX своим
   токеном из переменной окружения. Адрес эндпоинта секретом не является:
   знание адреса не даёт ничего, кроме возможности отправить заявку.

   Адрес относительный намеренно: Nginx проксирует /api/lead на сервис, и
   запрос остаётся на том же домене. Абсолютный адрес на поддомен тоже
   работает, но добавляет предварительный запрос CORS, а часть блокировщиков
   режет межсайтовые POST — на заявках это потерянные деньги.

   LEAD_ENDPOINT пустой — доставка на сервер выключена, форма открывает
   WhatsApp с готовым текстом. Так же она поступает, если сервер не ответил:
   заявка не теряется ни при какой поломке. */
window.LEAD_ENDPOINT = '/api/lead';

/* Запасной путь, когда сервер недоступен. */
window.LEAD_WA_PHONE = '79963470065';

/* ------------------------------------------------------------------ */

/* Единая отправка для всех форм сайта: попапа и форм на страницах услуг.
   Раньше у каждой формы была своя копия этой логики — восемь мест, которые
   расходились при каждой правке. Теперь место одно.

   Возвращает способ доставки, а не true. Разница существенная: «сервер
   принял» и «человеку открыли WhatsApp, и он, возможно, нажмёт отправить» —
   разные события, и показывать на них один и тот же экран нечестно.
     'srv'  — заявка у владельца, дальше ничего делать не нужно
     'wa'   — открыт WhatsApp с готовым текстом, отправляет человек
     'none' — браузер заблокировал окно, заявка не ушла никому  */
window.leadText = function (f) {
  return [
    '🟢 Новая заявка с сайта',
    '👤 Имя: ' + (f.name || '—'),
    '📞 Телефон: ' + (f.phone || '—'),
    f.comment ? '💬 ' + f.comment : '',
    f.source ? '📄 ' + f.source : '',
  ].filter(Boolean).join('\n');
};

window.leadSend = function (f) {
  /* Принимаем и объект с полями, и уже собранный текст строкой: формы на
     страницах услуг собирают его сами и имеют свои поля. */
  if (typeof f === 'string') f = { text: f };
  var text = f.text || window.leadText(f);
  var endpoint = window.LEAD_ENDPOINT || '';

  function wa() {
    var w = window.open('https://wa.me/' + (window.LEAD_WA_PHONE || '') +
      '?text=' + encodeURIComponent(text), '_blank');
    return w ? 'wa' : 'none';
  }

  if (!endpoint) return Promise.resolve(wa());

  var payload = {
    text: f.text || '',
    name: f.name || '',
    phone: f.phone || '',
    comment: f.comment || '',
    source: f.source || '',
    page: location.pathname,
    /* Honeypot: поле спрятано стилями, человек его не заполняет. */
    website: f.website || '',
  };

  /* Ограничение по времени: если сервер молчит, посетителю нельзя смотреть
     на крутилку бесконечно — через восемь секунд уходим в WhatsApp. */
  var timer;
  var timeout = new Promise(function (resolve) {
    timer = setTimeout(function () { resolve('timeout'); }, 8000);
  });

  return Promise.race([
    fetch(endpoint, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(payload),
    }).then(function (r) { return r.ok ? 'srv' : 'fail'; }).catch(function () { return 'fail'; }),
    timeout,
  ]).then(function (how) {
    clearTimeout(timer);
    return how === 'srv' ? 'srv' : wa();
  });
};
