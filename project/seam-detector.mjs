/* seam-detector.mjs — поиск тёмных полос на стыках блоков.
 *
 * Вынесено из check.mjs отдельным модулем ради check-seams.mjs: тот проверяет
 * саму проверку — подсовывает ей заведомый дефект и заведомый узор. Копия
 * правила в двух файлах рано или поздно разойдётся, и самотест начнёт
 * подтверждать не то правило, которое работает.
 *
 * История дефекта. Полоса между блоками возвращалась четырежды, каждый раз по
 * новой причине, и трижды я отчитывался, что всё чисто, — а владелец сайта
 * находил её глазами. Поэтому меряем пикселями снимка, а не вычисленными
 * стилями: у секции с градиентом backgroundColor прозрачный, и любая проверка
 * «по стилям» даёт ложный ноль.
 */

/* Средний тон строки по нескольким колонкам: одна колонка может попасть на
   картинку или текст и дать ложное срабатывание. */
export function rowTone(px, width, channels, y, xs) {
  let s = 0;
  for (const x of xs) {
    const i = (width * y + x) * channels;
    s += (px[i] + px[i + 1] + px[i + 2]) / 3;
  }
  return s / xs.length;
}

/* Порог заметности перепада тона. Полоса, которую владелец находил глазами,
   давала перепад около шести единиц; полторы — с запасом. */
const JUMP = 1.5;
/* Насколько «ровно» должно быть по обе стороны от границы. */
const FLAT = 0.6;
/* Минимальная высота полосы. Всё, что тоньше, — рисунок фона, а не дефект. */
const HOLD = 20;

/**
 * Ищет в полностраничном снимке границы, которые глаз видит как полосу.
 * @param {Buffer} data сырые пиксели (sharp .raw())
 * @param {{width:number,height:number,channels:number}} info
 * @returns {{side:string,y:number,d:number,up:number,dn:number}[]}
 */
export function findSeams(data, info) {
  /* Пробы берём в полях страницы. На отступах контента они попадали на текст
     и карточки и давали ложные срабатывания.

     Поля два, и меряются они порознь. Одной левой тройкой проверка видит
     только то, что дотянулось до левого края, а фоновые слои на главной
     смещены кто влево, кто вправо: пятно света в контактах, нити в
     сертификатах, блик в аудите. Полоса справа при замере слева выглядит как
     чистая страница. Складывать обе тройки в одно среднее нельзя — ступенька
     на одном краю размывается ровным тоном другого и уходит под порог. */
  const edges = {
    'слева': [6, 14, 22],
    'справа': [info.width - 23, info.width - 15, info.width - 7],
  };
  const hits = [];
  for (const [side, xs] of Object.entries(edges)) {
    const tone = (y) => rowTone(data, info.width, info.channels, y, xs);
    let last = -99;
    for (let y = HOLD + 2; y < info.height - HOLD - 2; y++) {
      const d = tone(y) - tone(y - 1);
      if (Math.abs(d) < JUMP) continue;
      /* Ступенька, а не градиент: тон держится ровно по обе стороны.
         Окна одинаковые и длиной в HOLD — это и есть то, что отличает полосу
         от рисунка. С коротким окном проверка считала полосой любую тонкую
         линию фона: дуга контура шириной в пару пикселей даёт точно такой же
         скачок тона, как настоящая граница, и на семи строках они
         неразличимы. Отдельная проба на середине окна нужна против частого
         узора: линии с шагом ровно в десять пикселей попадали и в -10, и в
         -20, обе давали одинаковый «ровный» отсчёт, и зона узора читалась
         как сплошная светлая плоскость. */
      if (Math.abs(tone(y - 1) - tone(y - HOLD)) > FLAT) continue;
      if (Math.abs(tone(y - 1) - tone(y - HOLD / 2)) > FLAT) continue;
      if (Math.abs(tone(y + HOLD) - tone(y + 2)) > FLAT) continue;
      if (Math.abs(tone(y + HOLD) - tone(y)) > FLAT) continue;
      if (y - last < 10) continue;
      last = y;
      hits.push({ side, y, d, up: tone(y - 1), dn: tone(y) });
    }
  }
  hits.sort((a, b) => a.y - b.y);
  return hits;
}

/* CSS, которым снимок готовится к замеру. Общий для проверки и самотеста —
   иначе они будут смотреть на разные страницы.

   Фиксированные элементы (шапка, плашка cookie, кнопка квиза) в
   полностраничном снимке впечатываются один раз, как правило у нижнего края,
   и создают ступеньку там, где на самой странице ничего нет. Это артефакт
   съёмки, а не дефект вёрстки.

   .mo-grain::before — плёночное зерно. Оно fixed и растянуто на inset: -50%,
   то есть в окне браузера всегда покрывает экран целиком и кромки не имеет.
   Но полностраничный снимок растягивает вьюпорт, зерно покрывает только
   верхнюю часть снимка, и его нижний край попадал в отчёт как полоса —
   каждый раз на другом y, потому что слой ещё и дрожит по кадрам анимации.

   Появление по прокрутке снимаем отдельно: полностраничный снимок делается с
   нулевой прокрутки, у всего ниже сгиба прогресс view() равен нулю, то есть
   opacity: 0. Без этого проверка стыков смотрела бы на пустой холст ниже
   первого экрана и находила «полосы» там, где просто ничего не нарисовано. */
